#!/usr/bin/env bash
# Runs inside a Debian container (local script and GitHub workflow). /dist holds the two
# sources and receives the .AppImage. Built on Debian 13 (libadwaita >= 1.6): the AppImage needs
# a glibc at least as recent as the container's (2.41). The Nautilus extension and the
# libcloudproviders declaration live in system directories and are not part of it.
# Tools are pinned by version and SHA-256 and run with APPIMAGE_EXTRACT_AND_RUN (no FUSE here).
set -euo pipefail
export DEBIAN_FRONTEND=noninteractive
LINUXDEPLOY_URL=https://github.com/linuxdeploy/linuxdeploy/releases/download/1-alpha-20251107-1/linuxdeploy-x86_64.AppImage
LINUXDEPLOY_SHA256=c20cd71e3a4e3b80c3483cef793cda3f4e990aca14014d23c544ca3ce1270b4d
GTK_PLUGIN_URL=https://raw.githubusercontent.com/linuxdeploy/linuxdeploy-plugin-gtk/7a3fbc31a9e5075073ff8790f26effbac5f84453/linuxdeploy-plugin-gtk.sh
GTK_PLUGIN_SHA256=b0f4cbc684a0103a9651f0955b635eaea0096b3a66c0f5a2c2aa337960375171
APPIMAGETOOL_URL=https://github.com/AppImage/appimagetool/releases/download/1.9.1/appimagetool-x86_64.AppImage
APPIMAGETOOL_SHA256=ed4ce84f0d9caff66f50bcca6ff6f35aae54ce8135408b3fa33abfc3cb384eb0

apt-get update
apt-get install -y --no-install-recommends build-essential gettext desktop-file-utils pkg-config \
    libgtk-4-dev libadwaita-1-dev libglib2.0-dev xz-utils ca-certificates curl file patchelf \
    librsvg2-common shared-mime-info cargo rustc
if ! dpkg --compare-versions "$(rustc --version | awk '{print $2}')" ge 1.92; then
    : "${RUSTUP_TOOLCHAIN:=stable}"
    apt-get remove -y cargo rustc
    curl --proto '=https' --tlsv1.2 -sSf https://sh.rustup.rs | sh -s -- -y --profile minimal --default-toolchain "$RUSTUP_TOOLCHAIN"
    export PATH="$HOME/.cargo/bin:$PATH"
fi
rustc --version

W=/tmp/build; rm -rf "$W"; mkdir -p "$W/tools"
fetch() { # fetch <url> <sha256> <file>
    curl --proto '=https' --tlsv1.2 -fsSL -o "$W/tools/$3" "$1"
    echo "$2  $W/tools/$3" | sha256sum -c -
    chmod +x "$W/tools/$3"
}
fetch "$LINUXDEPLOY_URL" "$LINUXDEPLOY_SHA256" linuxdeploy
fetch "$GTK_PLUGIN_URL" "$GTK_PLUGIN_SHA256" linuxdeploy-plugin-gtk.sh
fetch "$APPIMAGETOOL_URL" "$APPIMAGETOOL_SHA256" appimagetool
export APPIMAGE_EXTRACT_AND_RUN=1 ARCH=x86_64 PATH="$W/tools:$PATH"

tar -xJf "/dist/pdrive-for-linux-$VERSION.tar.xz" -C "$W"
S="$W/pdrive-for-linux-$VERSION"
tar -xJf "/dist/$NATIVE_ARCHIVE" -C "$W"
mkdir -p "$S/native/linux-x64"
cp "$W"/pdrive-native-linux-x64-*/* "$S/native/linux-x64/"
cd "$S/native/linux-x64" && sha256sum -c SHA256SUMS
cd "$S"

export PDSDK_LIB_DIR="$S/native/linux-x64"
cargo build --release --frozen --offline -p pdrived -p pdrive -p pdrive-app

A="$W/AppDir"
install -Dpm0755 target/release/pdrive target/release/pdrived target/release/pdrive-app -t "$A/usr/bin"
install -Dpm0644 packaging/man/*.1 -t "$A/usr/share/man/man1"
while read -r lang; do
    [[ -z "$lang" || "$lang" == \#* ]] && continue
    install -d "$A/usr/share/locale/$lang/LC_MESSAGES"
    msgfmt --check -o "$A/usr/share/locale/$lang/LC_MESSAGES/pdrive.mo" "po/$lang.po"
done < po/LINGUAS
install -d "$A/usr/share/doc/pdrive-for-linux"
cp THIRD_PARTY_NOTICES LICENSE THIRD_PARTY_CRATES.txt native/linux-x64/LICENSE-* licenses/*.tsv "$A/usr/share/doc/pdrive-for-linux/"

APP_ID=io.github.bpresles.PDrive.App
# The libraries are found through the rpath that linuxdeploy rewrites relative to the executables,
# except libproton_crypto.so, which the SDK loads by path: the hook below points it at the mount.
mkdir -p "$A/apprun-hooks"
cat > "$A/apprun-hooks/pdrive-lib-dir.sh" <<'EOT'
export PDRIVE_LIB_DIR="$APPDIR/usr/lib"
EOT
LD_LIBRARY_PATH="$PDSDK_LIB_DIR" DEPLOY_GTK_VERSION=4 linuxdeploy --appdir "$A" --plugin gtk \
    --executable "$A/usr/bin/pdrive-app" --executable "$A/usr/bin/pdrived" --executable "$A/usr/bin/pdrive" \
    --library "$PDSDK_LIB_DIR/libproton_drive_sdk.so" --library "$PDSDK_LIB_DIR/libproton_crypto.so" \
    --desktop-file "packaging/$APP_ID.desktop" \
    --icon-file "packaging/icons/hicolor/scalable/apps/$APP_ID.svg" --icon-filename "$APP_ID"

# The AppRun generated by linuxdeploy must source the hooks, else the crypto library is not found.
grep -q apprun-hooks "$A/AppRun" || { echo "AppRun does not run apprun-hooks/*.sh" >&2; exit 1; }
test -f "$A/usr/lib/libproton_crypto.so"
# No dependency may be left to the host, besides what linuxdeploy excludes on purpose (glibc...).
for b in pdrive pdrived pdrive-app; do
    ! ldd "$A/usr/bin/$b" | grep -F 'not found' || { echo "$b has unresolved libraries" >&2; exit 1; }
done

appimagetool --no-appstream "$A" "/dist/PDrive-for-Linux-$VERSION-x86_64.AppImage"
